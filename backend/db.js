// ============================================================
// All In One (Abc Authentic) - PostgreSQL connection pool
// All queries MUST use parameterized form: query(text, params).
// Never interpolate values into SQL strings.
// ============================================================
const { Pool } = require('pg');

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  max: 20,
  idleTimeoutMillis: 30000,
  connectionTimeoutMillis: 5000,
});

pool.on('error', (err) => {
  // Never log connection string or credentials
  console.error('[db] pool error:', err.message);
});

// Run a callback inside a transaction. Rolls back on error.
async function withTransaction(fn) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

module.exports = {
  query: (text, params) => pool.query(text, params),
  withTransaction,
  pool,
};
