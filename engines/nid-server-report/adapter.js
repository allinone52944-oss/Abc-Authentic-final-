'use strict';
/**
 * engines/nid-server-report/adapter.js — Abc Authentic adapter for the
 * Sign to Server Copy engine (NID form PDF / old v1/v2 report ->
 * v1 + v2 server-copy report PDFs).
 *
 * WRAPPING ONLY — the engine folder is an as-is copy of the
 * user-provided Server_Copy_Engine.zip contents (extract_input.py,
 * build_reports.py, report_v1_template.pdf, report_v2_template.pdf,
 * fonts/). No engine Python logic is modified here. The Windows
 * .bat orchestration, dlls/ and batch_build.py are NOT ported —
 * the site runs one job at a time through this adapter; the human
 * JSON check from the desktop flow becomes the review/edit step
 * in the frontend. The C:\Windows\Fonts paths in the scripts are
 * guarded fallbacks (os.path.exists) — on Linux the bundled
 * SolaimanLipi font is used. Deterministic: same input -> same output.
 *
 * Integration (backend mounts at /api/nid-server-report with JWT
 * auth + rate limit):
 *   extractFields(pdfBuffer) -> per-job dir work/jobs/<uuid>/
 *     becomes the process CWD for the engine scripts (they use
 *     relative "work/" paths, so each job is fully isolated). Runs:
 *       extract_input.py input.pdf -> work/input_data.json +
 *       work/input_images.json + work/images/
 *     Returns { ok, jobId, fields, images:[{name, dataUrl}] }.
 *   buildReports(jobId, fields, images) -> writes
 *     work/input_data.json, runs build_reports.py ->
 *     output/<NID>-v1.pdf + output/<NID>-v2.pdf.
 *     Returns { ok, v1Buffer, v2Buffer, nid, base }.
 *
 * Python deps (server): pip3 install pymupdf Pillow qrcode fonttools
 * (ddddocr/easyocr optional — scanned-PDF OCR fallback only).
 *
 * Security: jobId is UUID-validated and path-confined to the jobs
 * dir. Python stderr is never returned raw to the client (generic
 * error codes). Uploaded PII lives only in the per-job dir and is
 * pruned (keep last 50).
 *
 * The v2 QR (name + NID + DOB baked into the report) is a NEW QR
 * generated by build_reports.py — it is NOT the site's QR
 * photo-verify/fallback flow and is never wired into it.
 */

const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

const ENGINE_DIR = __dirname;
const JOBS_DIR = path.join(ENGINE_DIR, 'work', 'jobs');
const KEEP_JOBS = 50;
const TIMEOUT_MS = 120000;
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

let _config = {};

function jobDir(id) {
  return path.join(JOBS_DIR, id);
}

function resolveJobDir(id) {
  if (!UUID_RE.test(String(id || ''))) return null;
  const dir = path.resolve(jobDir(id));
  if (!dir.startsWith(path.resolve(JOBS_DIR) + path.sep)) return null;
  return dir;
}

function pruneJobs() {
  try {
    fs.mkdirSync(JOBS_DIR, { recursive: true });
    const entries = fs.readdirSync(JOBS_DIR)
      .map((n) => ({ n, t: fs.statSync(path.join(JOBS_DIR, n)).mtimeMs }))
      .sort((a, b) => b.t - a.t);
    for (const e of entries.slice(KEEP_JOBS)) {
      fs.rmSync(path.join(JOBS_DIR, e.n), { recursive: true, force: true });
    }
  } catch (_) { /* best effort */ }
}

function runPython(scriptName, args, cwd) {
  const script = path.join(ENGINE_DIR, scriptName);
  const r = spawnSync('python3', [script, ...args], {
    cwd,
    timeout: TIMEOUT_MS,
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
  });
  return {
    ok: r.status === 0,
    exitCode: r.status,
    signal: r.signal || null,
    timedOut: !!r.error && r.error.code === 'ETIMEDOUT',
    stdout: String(r.stdout || ''),
    // stderr kept for server logs only — never sent to client
    stderr: String(r.stderr || ''),
  };
}

function readImages(dir) {
  const out = [];
  try {
    const imgDir = path.join(dir, 'work', 'images');
    if (!fs.existsSync(imgDir)) return out;
    for (const f of fs.readdirSync(imgDir)) {
      if (!/\.(png|jpg|jpeg)$/i.test(f)) continue;
      const buf = fs.readFileSync(path.join(imgDir, f));
      if (buf.length > 8 * 1024 * 1024) continue; // sanity cap
      const ext = f.toLowerCase().endsWith('.png') ? 'png' : 'jpeg';
      out.push({ name: f, dataUrl: `data:image/${ext};base64,${buf.toString('base64')}` });
    }
  } catch (_) { /* best effort */ }
  return out;
}

// Core-data gate (same rule as the NID card engine, audit
// 2026-11-08 #1): a report is meaningless without a name, an ID
// number and a date of birth. A blank/garbage extract must never
// reach the build/charge step.
//   name = "Name(Bangla)" OR "Name(English)" non-empty
//   id   = "National ID" OR "Pin" non-empty
//   dob  = "Date of Birth" non-empty
// All three groups are required.
const CORE_NAME_KEYS = ['Name(Bangla)', 'Name(English)'];
const CORE_ID_KEYS = ['National ID', 'Pin'];
const CORE_DOB_KEYS = ['Date of Birth'];

const NO_CORE_DATA_MESSAGE = 'তথ্য অসম্পূর্ণ — নাম, জাতীয় পরিচয়পত্র নম্বর ও জন্মতারিখ ছাড়া সার্ভার কপি রিপোর্ট তৈরি করা যাবে না। সঠিক NID ফর্ম PDF আপলোড করুন। কোনো টাকা কাটা হয়নি।';

function _hasText(v) {
  return v !== null && v !== undefined && String(v).trim().length > 0;
}

function hasCoreData(fields) {
  if (!fields || typeof fields !== 'object' || Array.isArray(fields)) return false;
  const name = CORE_NAME_KEYS.some((k) => _hasText(fields[k]));
  const id = CORE_ID_KEYS.some((k) => _hasText(fields[k]));
  const dob = CORE_DOB_KEYS.some((k) => _hasText(fields[k]));
  return Boolean(name && id && dob);
}

// Bengali labels of the missing core-data groups (for diagnostics).
function missingCoreGroups(fields) {
  const f = (fields && typeof fields === 'object' && !Array.isArray(fields)) ? fields : {};
  const missing = [];
  if (!CORE_NAME_KEYS.some((k) => _hasText(f[k]))) missing.push('নাম');
  if (!CORE_ID_KEYS.some((k) => _hasText(f[k]))) missing.push('জাতীয় পরিচয়পত্র নম্বর');
  if (!CORE_DOB_KEYS.some((k) => _hasText(f[k]))) missing.push('জন্মতারিখ');
  return missing;
}

// Output filename base: the NID as ASCII digits (Bengali digits
// mapped), everything else stripped — a filename must never carry
// path characters. Falls back to "report" (same as build_reports.py).
function outputBase(fields) {
  const raw = String((fields && fields['National ID']) || '').trim();
  const ascii = raw.replace(/[০-৯]/g, (d) => String(d.charCodeAt(0) - 0x09E6));
  const digits = ascii.replace(/[^0-9]/g, '');
  return digits || 'report';
}

/**
 * Run the extract pipeline on an uploaded NID form / v1 / v2 PDF.
 * @param {Buffer} pdfBuffer
 * @param {string|number} ownerId
 * @returns {Promise<{ok:boolean, jobId?, fields?, images?, error?}>}
 */
async function extractFields(pdfBuffer, ownerId) {
  if (!pdfBuffer || !Buffer.isBuffer(pdfBuffer) || pdfBuffer.length < 100) {
    return { ok: false, error: 'INVALID_PDF' };
  }
  if (pdfBuffer.length > 20 * 1024 * 1024) {
    return { ok: false, error: 'PDF_TOO_LARGE' };
  }
  // Quick magic-byte check (real PDF)
  const head = pdfBuffer.slice(0, 5).toString('ascii');
  if (head !== '%PDF-') {
    return { ok: false, error: 'NOT_A_PDF' };
  }
  const id = crypto.randomUUID();
  const dir = resolveJobDir(id);
  try {
    fs.mkdirSync(path.join(dir, 'work'), { recursive: true });
    fs.writeFileSync(path.join(dir, 'input.pdf'), pdfBuffer);
    // Job ownership — only the creating user may build from this job
    if (ownerId) fs.writeFileSync(path.join(dir, '.owner'), String(ownerId));
    pruneJobs();

    const r = runPython('extract_input.py', ['input.pdf'], dir);
    if (!r.ok) {
      console.warn(`[nid-server-report] extract_input.py failed (job ${id}): exit=${r.exitCode} signal=${r.signal} timedOut=${r.timedOut}`);
      if (r.stderr) console.warn('[nid-server-report] stderr tail:', r.stderr.slice(-800));
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
      return { ok: false, error: r.timedOut ? 'ENGINE_TIMEOUT' : 'EXTRACT_FAILED' };
    }

    const dataPath = path.join(dir, 'work', 'input_data.json');
    if (!fs.existsSync(dataPath)) {
      return { ok: false, error: 'EXTRACT_FAILED' };
    }
    const fields = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
    // Core-data gate: a blank/garbage extract (input_data.json
    // present but no name/ID/DOB) is rejected here, before any job
    // exists to build from — so it can never reach the build/charge step.
    if (!hasCoreData(fields)) {
      console.warn(`[nid-server-report] extract has no core data (job ${id}): missing ${missingCoreGroups(fields).join(', ')}`);
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
      return { ok: false, error: 'NO_CORE_DATA' };
    }
    const images = readImages(dir);
    return { ok: true, jobId: id, fields, images };
  } catch (e) {
    console.warn('[nid-server-report] extractFields error:', e.message);
    try { if (dir) fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
    return { ok: false, error: 'EXTRACT_FAILED' };
  }
}

// Sanitize the (possibly edited) fields before they are written
// back to work/input_data.json for the build: scalar strings capped,
// address dicts sanitized key-by-key, unknown shapes dropped.
function sanitizeFields(fieldsJson) {
  const clean = {};
  const keys = Object.keys(fieldsJson).slice(0, 60);
  for (const k of keys) {
    const ks = String(k).slice(0, 120);
    const v = fieldsJson[k];
    if (v === null || v === undefined) {
      clean[ks] = '';
    } else if (typeof v === 'object' && !Array.isArray(v)) {
      const sub = {};
      for (const sk of Object.keys(v).slice(0, 20)) {
        const sv = v[sk];
        sub[String(sk).slice(0, 60)] = (sv === null || sv === undefined) ? '' : String(sv).slice(0, 500);
      }
      clean[ks] = sub;
    } else if (typeof v === 'string' || typeof v === 'number') {
      clean[ks] = String(v).slice(0, 2000);
    }
    // other types (arrays, booleans) are dropped — the builder
    // only reads strings and address dicts.
  }
  return clean;
}

/**
 * Build BOTH report PDFs (v1 + v2) from (possibly edited) fields.
 * @param {string} jobId
 * @param {object} fieldsJson  input_data.json shape (scalars + address dicts)
 * @param {Array} images  [{name, dataUrl}] — photo override; empty
 *   photo means the extracted photo is removed for the build.
 * @param {string|number} ownerId
 * @returns {Promise<{ok:boolean, v1Buffer?, v2Buffer?, nid?, base?, error?}>}
 */
async function buildReports(jobId, fieldsJson, images, ownerId) {
  const dir = resolveJobDir(jobId);
  if (!dir || !fieldsJson || typeof fieldsJson !== 'object' || Array.isArray(fieldsJson)) {
    return { ok: false, error: 'INVALID_REQUEST' };
  }
  if (!fs.existsSync(dir) || !fs.existsSync(path.join(dir, 'work', 'input_data.json'))) {
    return { ok: false, error: 'JOB_NOT_FOUND' };
  }
  // Job ownership check
  if (ownerId) {
    let owner = null;
    try { owner = fs.readFileSync(path.join(dir, '.owner'), 'utf8').trim(); } catch (_) {}
    if (owner && owner !== String(ownerId)) return { ok: false, error: 'NOT_YOUR_JOB' };
  }
  // Core-data gate (authoritative): the fields may have been edited
  // in the UI after a good extract, so a blanked-out build is
  // rejected here too — BEFORE any build runs.
  if (!hasCoreData(fieldsJson)) {
    console.warn(`[nid-server-report] build rejected, no core data (job ${jobId}): missing ${missingCoreGroups(fieldsJson).join(', ')}`);
    return { ok: false, error: 'NO_CORE_DATA' };
  }
  // Optional: replace the extracted photo with a user-uploaded one.
  // build_reports.py falls back to work/images/photo.png when
  // input_images.json has no "photo", so removing the photo must
  // delete the file itself — otherwise the old photo would print.
  if (Array.isArray(images)) {
    const imgDir = path.join(dir, 'work', 'images');
    try { fs.mkdirSync(imgDir, { recursive: true }); } catch (_) {}
    const passedNames = new Set();
    for (const im of images.slice(0, 10)) {
      if (!im || !im.name || !im.dataUrl || typeof im.dataUrl !== 'string') continue;
      const safeName = path.basename(String(im.name)).replace(/[^a-zA-Z0-9._-]/g, '_').slice(0, 80);
      passedNames.add(safeName);
      const m = im.dataUrl.match(/^data:image\/(png|jpe?g|webp);base64,(.+)$/);
      if (!m || m[2].length > 14 * 1024 * 1024) continue; // cap at ~10MB decoded
      try { fs.writeFileSync(path.join(imgDir, safeName), Buffer.from(m[2], 'base64')); } catch (e) {}
    }
    if (!passedNames.has('photo.png') && fs.existsSync(path.join(imgDir, 'photo.png'))) {
      try { fs.unlinkSync(path.join(imgDir, 'photo.png')); } catch (_) {}
    }
  }
  const clean = sanitizeFields(fieldsJson);
  const base = outputBase(clean);
  try {
    fs.writeFileSync(path.join(dir, 'work', 'input_data.json'), JSON.stringify(clean, null, 1), 'utf8');
    const r = runPython('build_reports.py', [], dir);
    if (!r.ok) {
      console.warn(`[nid-server-report] build_reports.py failed (job ${jobId}): exit=${r.exitCode} signal=${r.signal} timedOut=${r.timedOut}`);
      if (r.stderr) console.warn('[nid-server-report] stderr tail:', r.stderr.slice(-800));
      return { ok: false, error: r.timedOut ? 'ENGINE_TIMEOUT' : 'BUILD_FAILED' };
    }
    const v1Path = path.join(dir, 'output', base + '-v1.pdf');
    const v2Path = path.join(dir, 'output', base + '-v2.pdf');
    if (!fs.existsSync(v1Path) || !fs.existsSync(v2Path)) {
      return { ok: false, error: 'BUILD_FAILED' };
    }
    const v1Buffer = fs.readFileSync(v1Path);
    const v2Buffer = fs.readFileSync(v2Path);
    if (v1Buffer.length < 1000 || v2Buffer.length < 1000) {
      return { ok: false, error: 'BUILD_FAILED' };
    }
    return { ok: true, v1Buffer, v2Buffer, nid: String(clean['National ID'] || '').trim(), base };
  } catch (e) {
    console.warn('[nid-server-report] buildReports error:', e.message);
    return { ok: false, error: 'BUILD_FAILED' };
  }
}

/**
 * Check a job exists and belongs to the user (for /create, which
 * charges before the build runs — a dead/foreign job must never
 * reach the charge step).
 * @returns {Promise<{ok:boolean, error?}>}
 */
async function validateJob(jobId, ownerId) {
  const dir = resolveJobDir(jobId);
  if (!dir || !fs.existsSync(dir) || !fs.existsSync(path.join(dir, 'work', 'input_data.json'))) {
    return { ok: false, error: 'JOB_NOT_FOUND' };
  }
  if (ownerId) {
    let owner = null;
    try { owner = fs.readFileSync(path.join(dir, '.owner'), 'utf8').trim(); } catch (_) {}
    if (owner && owner !== String(ownerId)) return { ok: false, error: 'NOT_YOUR_JOB' };
  }
  return { ok: true };
}

function init(config) {
  _config = Object.assign({}, config || {});
  try { fs.mkdirSync(JOBS_DIR, { recursive: true }); } catch (_) {}
  // Preflight: python3 + required deps present?
  // (fonttools is best-effort on Linux — bn_bold() only needs it
  // for a .ttc font, and the bundled font is a .ttf — so it is
  // not part of the readiness check.)
  try {
    const r = spawnSync('python3', ['-c', 'import pymupdf, PIL, qrcode; print("ok")'],
      { timeout: 15000, encoding: 'utf8' });
    if (r.status === 0) {
      console.log('[nid-server-report] engine ready (python deps ok)');
    } else {
      console.warn('[nid-server-report] python deps missing — run: pip3 install pymupdf Pillow qrcode fonttools');
    }
  } catch (e) {
    console.warn('[nid-server-report] python3 not available:', e.message);
  }
  return { ok: true };
}

function getInfo() {
  return {
    id: 'nid-server-report',
    name: 'Sign to Server Copy',
    name_bn: 'সাইন টু সার্ভার কপি',
    version: '1.0.0',
    capabilities: ['extract-fields', 'report-pdf'],
    mode: 'as-is-wrap',
    input: { pdf: 'NID form PDF (or old v1/v2 report)' },
  };
}

module.exports = { init, getInfo, extractFields, buildReports, validateJob, hasCoreData, missingCoreGroups, outputBase, NO_CORE_DATA_MESSAGE };
