# -*- coding: utf-8 -*-
"""Build assets/fonts.css — embedded @font-face (woff2, base64 data URLs).

Embedded (NOT guaranteed on every PC):
  - SutonnyOMJ          (custom Bengali font)
  - Calibri / Candara / Constantia  (Office fonts, not Windows-inbox)
  - Nirmala UI          (body default; inbox on Win8.1+ but embedded for
                         Mac/old-Windows parity)
Left as system fonts (Windows + macOS inbox): Verdana, Tahoma,
Trebuchet MS, Arial, Times New Roman.

Subset = full Bengali block + Latin-1 + Latin Ext + General Punctuation +
currency + fi/ff/fl ligature chars, ALL layout features kept (Bengali
shaping + ligatures must stay identical to the system-font render).
"""
import base64, io, os, subprocess, sys, tempfile
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

FONTS = 'C:\\Windows\\Fonts'
OUT = r'C:\Users\pRANESHWAR\Desktop\BDRIS Scrapper\assets\fonts.css'

UNICODES = (
    'U+0020-017F,'      # ASCII + Latin-1 + Latin Ext-A
    'U+0180-024F,'      # Latin Ext-B
    'U+0300-036F,'      # combining diacritics
    'U+2000-206F,'      # General Punctuation (quotes, dashes, ellipsis)
    'U+20A0-20BF,'      # currency
    'U+2122,'           # trademark
    'U+FB00-FB04,'      # ff fi fl ffi fffl ligatures
    'U+0980-09FF'       # FULL Bengali block (dynamic data)
)

# (source, font-number/-1, css-family, weight, style, tag)
JOBS = [
    (os.path.join(FONTS, 'SutonnyOMJ.ttf'), -1, 'SutonnyOMJ',      '400', 'normal', 'sutonny'),
    (os.path.join(FONTS, 'calibri.ttf'),    -1, 'Calibri',         '400', 'normal', 'calibri'),
    (os.path.join(FONTS, 'Candara.ttf'),    -1, 'Candara',         '400', 'normal', 'candara'),
    (os.path.join(FONTS, 'constan.ttf'),    -1, 'Constantia',      '400', 'normal', 'constan'),
    (os.path.join(FONTS, 'constanb.ttf'),   -1, 'Constantia',      '700', 'normal', 'constanb'),
]

def ttc_faces(path):
    from fontTools.ttLib import TTCollection
    col = TTCollection(path)
    out = []
    for i, f in enumerate(col.fonts):
        name = f['name'].getDebugName(4) or ''
        out.append((i, name))
    return out

def main():
    # Nirmala UI faces from the TTC collection
    ttc = os.path.join(FONTS, 'Nirmala.ttc')
    faces = ttc_faces(ttc)
    print('Nirmala.ttc faces:', faces)
    want = {'Nirmala UI': {}, 'Nirmala UI Bold': '700', 'Nirmala UI Italic': ('400', 'italic')}
    for i, name in faces:
        if name == 'Nirmala UI':
            JOBS.append((ttc, i, 'Nirmala UI', '400', 'normal', 'nirmala'))
        elif name == 'Nirmala UI Bold':
            JOBS.append((ttc, i, 'Nirmala UI', '700', 'normal', 'nirmalab'))
        elif name == 'Nirmala UI Italic':
            JOBS.append((ttc, i, 'Nirmala UI', '400', 'italic', 'nirmalai'))

    rules, total = [], 0
    for path, num, family, weight, style, tag in JOBS:
        with tempfile.TemporaryDirectory() as td:
            out_ttf = os.path.join(td, tag + '.woff2')
            cmd = [
                sys.executable, '-m', 'fontTools.subset', path,
                '--unicodes=' + UNICODES,
                '--layout-features=*',
                '--flavor=woff2',
                '--output-file=' + out_ttf,
            ]
            if num >= 0:
                cmd.insert(4, '--font-number=%d' % num)
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                print('FAIL', tag, r.stderr[-800:])
                sys.exit(1)
            data = open(out_ttf, 'rb').read()
        b64 = base64.b64encode(data).decode('ascii')
        total += len(data)
        print('  %-10s %-14s w%s %-7s %6.1f KB -> b64 %6.1f KB' % (
            tag, family, weight, style, len(data)/1024, len(b64)/1024))
        rules.append(
            "@font-face{font-family:'%s';font-style:%s;font-weight:%s;font-display:block;"
            "src:url(data:font/woff2;base64,%s) format('woff2');}" % (family, style, weight, b64))

    css = ('/* EMBEDDED FONTS - generated by make-fonts.py. Do not edit.\n'
           '   All certificate fonts live in this file: same render on every PC,\n'
           '   no font install needed. Regenerate: python make-fonts.py */\n'
           + '\n'.join(rules) + '\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='ascii', newline='\n').write(css)
    print('WROTE', OUT, '%.1f KB (raw woff2 total %.1f KB), rules:' % (len(css)/1024, total/1024), len(rules))

if __name__ == '__main__':
    main()
